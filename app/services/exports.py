"""CSV exports and printable QR codes (PROMPT §6).

CSV: UTF-8 with BOM, delimiter `CSV_DELIMITER`, decimal separator `CSV_DECIMAL_SEPARATOR`,
proper quoting, and neutralization of spreadsheet formula injection in every *text* cell (names,
notes, ...). Amounts and dates are generated by this module, never user text, so they are not
prefixed. Both exports are restricted to the administrator's scope and audited, so they must be
called with a write session.

QR: pure-Python `segno`; the SVG is composed here (label above, URL below) using presentation
attributes only (no inline styles, so it works under the strict CSP).
"""

