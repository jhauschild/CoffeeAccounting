BOM = "﻿"
FORMULA_PREFIXES = ("=", "+", "-", "@", "\t", "\r")


# ----- CSV ------------------------------------------------------------------------------------
def csv_text(value) -> str:
    """Text cell: prefix `'` when a spreadsheet could read it as a formula (also after leading blanks)."""
    s = "" if value is None else str(value)
    probe = s.lstrip(" ")
    if probe.startswith(FORMULA_PREFIXES) or s.startswith(FORMULA_PREFIXES):
        return "'" + s
    return s

_ATTR_ENTITIES = {'"': "&quot;", "'": "&#x27;"}  # for values inside a quoted attribute


def _money(cents: int | None) -> str:
    return "" if cents is None else format_amount(cents, decimal_separator=get_settings().csv_decimal_separator)


def _local(dt: datetime | None) -> str:
    return "" if dt is None else format_local(dt, "%Y-%m-%d %H:%M")


def _render(header: list[str], rows: list[list[str]]) -> bytes:
    buf = io.StringIO()
    writer = csv.writer(buf, delimiter=get_settings().csv_delimiter, quoting=csv.QUOTE_MINIMAL, lineterminator="\r\n")
    writer.writerow(header)
    writer.writerows(rows)
    return (BOM + buf.getvalue()).encode("utf-8")


def users_csv(
    db: Session, admin: AdminUser, *, q: str | None = None, chair_id: uuid.UUID | None = None,
    status: str | None = None, sort: str = "balance", direction: str | None = None, ip: str | None = None,
) -> bytes:
    """The user table with the current filters, all pages. Audited (`export.users_csv`)."""
    page = stats.list_users(db, admin, q=q, chair_id=chair_id, status=status, sort=sort, direction=direction,
                            page=1, page_size=None)
    header = [t(f"admin.csv.{k}") for k in ("name", "chair", "shots", "consumed", "paid", "balance",
                                            "last_activity", "status")]
    rows = [[csv_text(r.display_name), csv_text(r.chair_short), r.shots, _money(r.consumed_cents),
             _money(r.paid_cents), _money(r.balance_cents), _local(r.last_activity_at), csv_text(r.status)]
            for r in page.rows]
    audit.log(db, actor_type="admin", actor_id=admin.id, action="export.users_csv", target_type="export",
              metadata={"rows": len(rows), "q": (q or "")[:64], "chair_id": str(chair_id) if chair_id else None,
                        "status": status, "sort": page.sort, "direction": page.direction}, ip=ip)
    return _render(header, rows)


def local_range_bounds(date_from: date | None, date_to: date | None) -> tuple[datetime | None, datetime | None]:
    """Inclusive local calendar dates -> half-open UTC bounds."""
    tz = get_settings().tz

    def midnight(d: date) -> datetime:
        return datetime.combine(d, time.min, tzinfo=tz).astimezone(UTC)

    return (midnight(date_from) if date_from else None,
            midnight(date_to + timedelta(days=1)) if date_to else None)


def ledger_csv(
    db: Session, admin: AdminUser, *, date_from: date | None = None, date_to: date | None = None,
    chair_id: uuid.UUID | None = None, ip: str | None = None,
) -> bytes:
    """Consumption and payment events (oldest first) in a local date range and event chair.
    Audited (`export.ledger_csv`)."""
    from app.services import authz

    stats.check_chair_filter(db, admin, chair_id)
    visible = authz.visible_chair_ids(db, admin)
    start, end = local_range_bounds(date_from, date_to)
    ce, pe = ConsumptionEvent, PaymentEvent

    def scoped(model, stmt):
        clauses = [c for c in (stats._scope_user_ids(visible, model.user_id),
                               model.chair_id == chair_id if chair_id else None,
                               model.created_at >= start if start else None,
                               model.created_at < end if end else None) if c is not None]
        return stmt.where(*clauses)

    cons = db.execute(scoped(ce, select(ce, User.display_name, Chair.short_name)
                             .join(User, User.id == ce.user_id).join(Chair, Chair.id == ce.chair_id))).all()
    pays = db.execute(scoped(pe, select(pe, User.display_name, Chair.short_name)
                             .join(User, User.id == pe.user_id).join(Chair, Chair.id == pe.chair_id))).all()
    admin_ids = {e.admin_id for e, _, _ in cons if e.admin_id} | {p.admin_id for p, _, _ in pays}
    names = {a.id: a.username for a in db.scalars(select(AdminUser).where(AdminUser.id.in_(admin_ids)))} if admin_ids else {}

    entries = []
    for e, name, chair in cons:
        entries.append((e.created_at, str(e.id), [
            _local(e.created_at), csv_text(e.type), csv_text(name), csv_text(chair), e.quantity,
            _money(e.unit_price_cents), _money(e.amount_cents), csv_text(e.note),
            csv_text(names.get(e.admin_id, "")), str(e.id)]))
    for p, name, chair in pays:
        entries.append((p.created_at, str(p.id), [
            _local(p.created_at), csv_text("correction" if p.correction_of_id else ("bookkeeping" if p.kind == "bookkeeping" else "payment")), csv_text(name),
            csv_text(chair), "", "", _money(p.amount_cents), csv_text(p.note), csv_text(names.get(p.admin_id, "")),
            str(p.id)]))
    entries.sort(key=lambda x: (x[0], x[1]))
    header = [t(f"admin.csv.{k}") for k in ("date", "type", "name", "chair", "quantity", "unit_price", "amount",
                                            "note", "admin", "event_id")]
    audit.log(db, actor_type="admin", actor_id=admin.id, action="export.ledger_csv", target_type="export",
              metadata={"rows": len(entries), "from": date_from.isoformat() if date_from else None,
                        "to": date_to.isoformat() if date_to else None,
                        "chair_id": str(chair_id) if chair_id else None}, ip=ip)
    return _render(header, [row for _, _, row in entries])


def group_balances_csv(db: Session, admin: AdminUser, *, ip: str | None = None) -> bytes:
    """Group balances per group admin (current and former) and per chair roll-up, signed amounts.
    Head admin only (`Forbidden`); audited (`export.group_balances_csv`)."""
    authz.require_global(admin)
    balances = groups.list_group_balances(db)
    rollup = groups.chair_rollup(db)
    header = [t(f"admin.csv.{k}") for k in ("row_kind", "group_admin", "chair", "collected", "handed_over",
                                            "held", "flag")]
    rows = []
    for b in balances:
        flags = ([] if b.is_current else [t("admin.csv.flag_former")]) + \
                ([t("admin.csv.flag_negative")] if b.negative else [])
        rows.append([csv_text(t("admin.csv.kind_admin")), csv_text(b.display_name or b.username),
                     csv_text(b.chair_short_name or ""), _money(b.collected_cents), _money(b.remitted_cents),
                     _money(b.held_cents), csv_text("; ".join(flags))])
    for c in rollup:
        rows.append([csv_text(t("admin.csv.kind_chair")), "", csv_text(c.chair_short_name),
                     _money(c.collected_cents), _money(c.remitted_cents), _money(c.held_cents),
                     csv_text(t("admin.csv.flag_negative") if c.negative else "")])
    audit.log(db, actor_type="admin", actor_id=admin.id, action="export.group_balances_csv", target_type="export",
              metadata={"rows": len(rows)}, ip=ip)
    return _render(header, rows)


def csv_filename(kind: str, now: datetime | None = None) -> str:
    return f"coffee-{kind}-{format_local(now or utcnow(), '%Y%m%d-%H%M')}.csv"


# ----- QR codes -------------------------------------------------------------------------------
def qr_urls() -> dict[str, str]:
    """The two canonical scan URLs (PROMPT §3); they are the only content of the QR codes."""
    base = get_settings().public_base_url
    return {"single": f"{base}/coffee/single", "double": f"{base}/coffee/double"}


def qr_svg(url: str, label: str | None, *, caption: str | None = None, standalone: bool = True) -> str:
    """Labeled SVG QR code: large `label` above the code, `caption` (default: the URL) below.

    `standalone=True` includes the XML namespace and a title for use as a file; inline use in HTML
    omits nothing that matters. Only presentation attributes are used (no `style`, no scripts).
    """
    qr = segno.make(url, error="m", micro=False)
    border = 4
    size = len(qr.matrix)
    width = size + 2 * border
    label_h = 12 if label else 0
    caption_h = 5 if label else 0
    height = width + label_h + caption_h
    parts = []
    for y, row in enumerate(qr.matrix):
        x = 0
        while x < size:
            if row[x]:
                start = x
                while x < size and row[x]:
                    x += 1
                parts.append(f"M{start + border} {y + border + label_h}h{x - start}v1h-{x - start}z")
            else:
                x += 1
    ns = ' xmlns="http://www.w3.org/2000/svg"' if standalone else ""
    font = 'font-family="Arial, Helvetica, sans-serif"'
    name = label or "QR code"
    out = [
        f'<svg{ns} viewBox="0 0 {width} {height}" role="img" aria-label="{escape(name, _ATTR_ENTITIES)} QR code" '
        f'class="qr-svg" shape-rendering="crispEdges">',
        f"<title>{escape(name + ': ' + url) if label else escape(name)}</title>",
        f'<rect width="{width}" height="{height}" fill="#fff"/>',
    ]
    if label:
        out.append(f'<text x="{width / 2}" y="{label_h - 2.5}" text-anchor="middle" {font} font-weight="700" '
                   f'font-size="9" fill="#000">{escape(label)}</text>')
    out.append(f'<path d="{"".join(parts)}" fill="#000"/>')
    if label:
        caption_text = escape(caption if caption is not None else url)
        out.append(f'<text x="{width / 2}" y="{height - 1.5}" text-anchor="middle" {font} font-size="2.2" '
                   f'fill="#000">{caption_text}</text>')
    out.append("</svg>")
    return "".join(out)


def write_qr_files(out_dir) -> list[str]:
    """Write `single.svg` and `double.svg` into `out_dir` (CLI `qr --out DIR`); returns the file names."""
    from pathlib import Path

    directory = Path(out_dir)
    directory.mkdir(parents=True, exist_ok=True)
    written = []
    for kind, url in qr_urls().items():
        path = directory / f"coffee-{kind}.svg"
        path.write_text(qr_svg(url, t(f"admin.qr.label_{kind}")), encoding="utf-8")
        written.append(path.name)
    return written
